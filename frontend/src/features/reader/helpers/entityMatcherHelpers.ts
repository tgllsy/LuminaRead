const ENTITY_KEYS = Object.keys(ENTITY_DICTIONARY).sort((a, b) => b.length - a.length)

/**
 * 提炼段落中的实体/成语词条，严格控制每段最多 3 个，避免阅读干扰
 */
export function findEntitiesInText(text: string, maxEntities = 3): RecognizedEntity[] {
  if (!text || text.length < 4) return []

  const results: RecognizedEntity[] = []
  const occupiedRanges: Array<[number, number]> = []

  const isOccupied = (s: number, e: number) => {
    return occupiedRanges.some(([os, oe]) => Math.max(s, os) < Math.min(e, oe))
  }

  for (const term of ENTITY_KEYS) {
    if (results.length >= maxEntities) break
    let searchPos = 0
    while (searchPos < text.length) {
      const idx = text.indexOf(term, searchPos)
      if (idx === -1) break

      const end = idx + term.length
      if (!isOccupied(idx, end)) {
        results.push({
          term,
          start: idx,
          end,
          quickDef: ENTITY_DICTIONARY[term],
        })
        occupiedRanges.push([idx, end])
        if (results.length >= maxEntities) break
      }
      searchPos = end
    }
  }

  return results.sort((a, b) => a.start - b.start)
}
